#pragma once
#include <unistd.h>
#include <iostream>

namespace maplesu::sdk {
/***************************************************************************
 * 读取 MapleSU 日志
 * 返回: OK 表示成功；其它值为错误码
 ***************************************************************************/
KModErr read_maplesu_log(std::string& out);

/***************************************************************************
* 设置 MapleSU 日志开关
*       enable       true 表示开启日志，false 表示关闭日志
* 返回: OK 表示设置成功；其他值为错误码
***************************************************************************/
KModErr set_maplesu_log_enabled(bool enable);

/***************************************************************************
* 查询 MapleSU 日志是否开启
* 返回: true 表示开启日志，false表示关闭日志
***************************************************************************/
bool is_maplesu_log_enabled();

/***************************************************************************
* 清空一次 MapleSU 日志
* 返回: OK 表示清空成功；其他值为错误码
***************************************************************************/
KModErr clear_maplesu_log();
}
